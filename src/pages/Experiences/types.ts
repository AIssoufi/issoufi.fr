/**
 * One piece of a paragraph of `.data/experiences.json`: a text named by its translation key,
 * which the page writes after the previous piece, in bold when `isStrong` is true.
 */
export interface TextSegmentData {
  /** Translation key of the text, e.g. `exp.sewanLead.intro1`. */
  key?: string;
  /** Whether the text is in bold, as a company or a client name. @default false */
  isStrong?: boolean;
}

/** A project carried out within a role: a block with a title, a status badge and a description. */
export interface ProjectData {
  /** Translation key of the project name. */
  titleKey?: string;
  /** Translation key of its status badge, e.g. "Livré dans les délais". */
  stateKey?: string;
  /** Description of the project, piece by piece. */
  description?: TextSegmentData[];
  /** Translation keys of the bullet points under the description, in order. */
  bulletKeys?: string[];
  /** Technologies of the project, proper names written the same in every language. */
  technologies?: string[];
}

/**
 * One job at a company. Its description shows, in this order, the introduction, the bullet
 * points, the projects and the technologies.
 */
export interface RoleData {
  /** Translation key of the job title. */
  titleKey?: string;
  /** Translation key of its start, a month and a year, e.g. "juin 2021". */
  startKey?: string;
  /** Translation key of its end, in the same format, or "Aujourd’hui". */
  endKey?: string;
  /** Introduction of the role, piece by piece. */
  intro?: TextSegmentData[];
  /** Translation keys of the bullet points under the introduction, in order. */
  bulletKeys?: string[];
  /** Projects of the role, in order. */
  projects?: ProjectData[];
  /** Technologies of the role, proper names written the same in every language. */
  technologies?: string[];
}

/**
 * One company of the timeline, as stored in `.data/experiences.json`, with translation keys in
 * place of its texts, so that every language shows its own. The Experiences page and the CV
 * generated by `pnpm cv` (`scripts/cv/`) both read it.
 */
export interface ExperienceData {
  /** Unique name of the company, used as the React key. */
  id: string;
  /** Translation key of the company name, also the alt text of its logo. */
  nameKey?: string;
  /** Translation key of the contract type, e.g. "CDI". */
  contractKey?: string;
  /** Translation key of the city and department, e.g. "Paris (75)". */
  cityKey?: string;
  /**
   * Absolute URL of the company logo, a square WebP file of `public/`, twice as wide as the
   * `LOGO_SIZE_PX` it shows at (`JobSummary/constants.ts`).
   */
  logoUrl?: string;
  /**
   * Successive roles at the company, most recent first: several make a group on the timeline.
   * The timeline writes the period of each role from its own dates, a single role included.
   */
  roles?: RoleData[];
}
