import { useTranslation } from 'react-i18next';

import experiencesData from './.data/experiences.json';
import CompanyEntry from './CompanyEntry';
import { BACKGROUND_IMAGE_URL } from './constants';
import type { ExperienceData } from './types';

import { ExperiencesPage, PageHeader, PageTitle, Timeline } from './Experiences.styled';

/** Companies of the timeline, most recent first, with the keys of their texts. */
const EXPERIENCES: ExperienceData[] = experiencesData.experiences;

/**
 * Experiences page: a timeline of the professional experiences, most recent first, with their
 * roles, projects and technologies. They come from `.data/experiences.json`, which the CV
 * generated by `pnpm cv` reads too, and their texts from the `exp` translations. The timeline is
 * a list of the companies, and its headings follow each other level by level: the `h1` of the
 * page, a `h2` per company, a `h3` per job and a `h4` per project.
 */
export const Experiences = () => {
  const { t } = useTranslation();

  return (
    <ExperiencesPage backgroundImage={BACKGROUND_IMAGE_URL}>
      <PageHeader>
        <PageTitle>{t('exp.pageTitle')}</PageTitle>
      </PageHeader>
      <Timeline data-timeline-line="before">
        {EXPERIENCES.map(experience => (
          <CompanyEntry
            key={experience.id}
            experience={experience}
          />
        ))}
      </Timeline>
    </ExperiencesPage>
  );
};
